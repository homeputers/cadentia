export const normalizeLocale = (value?: string | null): SupportedLocale => {
    const language = (value ?? 'en').toLowerCase().split(/[-_]/)[0];
    return language === 'es' || language === 'pt' ? language : 'en';
};

const englishMessageValue = (source: string): string | undefined => {
    const entry = Object.entries(messages.en).find(([, value]) => typeof value === 'string' && value === source);
    return entry?.[0];
};

export const translateText = (locale: string | null | undefined, source: string): string => {
    const normalized = normalizeLocale(locale);
    if (normalized === 'es') {
        const humanized = source.replaceAll('_', ' ').replaceAll('.', ' ').toLowerCase().replace(/^./, (c) => c.toUpperCase());
        const direct = spanishPhrases[source] ?? codeTranslations[source] ?? codeTranslations[humanized];
        if (direct) return direct;
        if (source.includes(',')) {
            const translatedParts = source.split(',').map((part) => {
                const trimmed = part.trim();
                const partHumanized = trimmed.replaceAll('_', ' ').replaceAll('.', ' ').toLowerCase().replace(/^./, (c) => c.toUpperCase());
                return codeTranslations[trimmed] ?? codeTranslations[partHumanized];
            });
            if (translatedParts.every(Boolean)) return translatedParts.join(', ');
        }
        return source;
    }
    const key = englishMessageValue(source) as TranslationKey | undefined;
    if (key) return translate(locale, key);
    return source;
};

export const localizedLabel = (locale: string | null | undefined, value?: string | null): string => {
    if (!value) return translateText(locale, 'None');
    const humanized = value.replaceAll('_', ' ').replaceAll('.', ' ').toLowerCase().replace(/^./, (c) => c.toUpperCase());
    return translateText(locale, codeTranslations[value] ?? codeTranslations[humanized] ?? humanized);
};

export const localizedRole = (locale: string | null | undefined, role: string): string => {
    if (normalizeLocale(locale) === 'es') return roleTranslations[role] ?? localizedLabel(locale, role);
    return role.replaceAll('_', ' ');
};

export const localizedCapability = (locale: string | null | undefined, capability: string): string => {
    if (normalizeLocale(locale) === 'es') return capabilityTranslations[capability] ?? localizedLabel(locale, capability);
    return capability.replaceAll('_', ' ');
};

const localizedPropNames = ['aria-label', 'title', 'placeholder', 'label', 'description', 'eyebrow', 'caption', 'acknowledgement', 'versionContext', 'defaultValue'];

const localizeNode = (node: ReactNode, locale: SupportedLocale): ReactNode => {
    if (typeof node === 'string') return translateText(locale, node);
    if (Array.isArray(node)) return node.map((child) => localizeNode(child, locale));
    if (!isValidElement(node)) return node;
    const props = { ...(node.props as Record<string, unknown>) };
    if ('children' in props) props.children = localizeNode(props.children as ReactNode, locale);
    for (const propName of localizedPropNames) {
        if (typeof props[propName] === 'string') props[propName] = translateText(locale, props[propName] as string);
    }
    for (const propName of ['columns', 'facts']) {
        if (Array.isArray(props[propName])) props[propName] = (props[propName] as unknown[]).map((value) => typeof value === 'string' ? translateText(locale, value) : value);
    }
    return cloneElement(node, props);
};

export const LocalizedView = ({ children }: { children: ReactNode }) => {
    const { locale } = useI18n();
    return <>{localizeNode(children, locale)}</>;
};

export const translate = (locale: string | null | undefined, key: TranslationKey): string => {
    const normalized = normalizeLocale(locale);
    const value = messages[normalized][key];
    return typeof value === 'string' ? value : messages.en[key] as string;
};

type I18nContextValue = { locale: SupportedLocale; t: (key: TranslationKey) => string };
const I18nContext = createContext<I18nContextValue>({ locale: 'en', t: (key) => translate('en', key) });

export const I18nProvider = ({ locale, children }: { locale?: string | null; children: ReactNode }) => {
    const normalized = normalizeLocale(locale);
    useEffect(() => {
        document.documentElement.lang = normalized;
    }, [normalized]);
    return <I18nContext.Provider value={{ locale: normalized, t: (key) => translate(normalized, key) }}>{children}</I18nContext.Provider>;
};

export const useI18n = () => useContext(I18nContext);

